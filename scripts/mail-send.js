#!/usr/bin/env node
"use strict";

// The mail sent to the iPhone (アストラの正式化案 ①④, よしひろさん「この形で作って」2026-11-26).
// The normal Chat does not read GitHub, so the mail carries the ask, its earlier rounds and its files, whole.
// Line 1 is the one-time token: the iPhone shortcut takes it off before ChatGPT and puts it back before the answer.
// Only its tag (mail-route.js tagOf) is written in GitHub, never the token.
const { planSend, tagOf } = require("./mail-route");

const OWNER = "amukutsurogiwork-oss";
const VERSION = 1;
// What the Chat may read in one go is about 5,000 characters (measured 2026-11-15); the mail stays at 90%.
const MAX_MAIL_CHARS = 4500;
// The iPhone automation starts on this subject (from Monet's address only).
const MAIL_SUBJECT = "AMONE-TEST-RETURN";

const first = (b) => String(b || "").replace(/^﻿/, "").split(/\r?\n/)[0].trim();
const fields = (line) => {
  const out = {};
  for (const kv of line.replace(/^\[[^\]]+\]\s*/, "").split(/\s+/)) {
    const i = kv.indexOf("=");
    if (i > 0) out[kv.slice(0, i)] = kv.slice(i + 1);
  }
  return out;
};
const len = (s) => [...s].length;
// The signature GitHub posts get is not part of the ask (Astra found the packet and the comment differ by it).
const stripFooter = (b) => String(b || "").replace(/\r\n?/g, "\n").replace(/\n*---\n_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)_\s*$/, "").replace(/\s+$/, "");
const tokenLine = (token) => `⟦AMONE-TOKEN ${token}⟧`;
const endOfAnswer = (request, round) => `【回答おわり request=${request} round=${round}】`;

// readFile(path, sha) returns the file's text at that commit. Returns { ok, subject, body, chars, send, sendHead } or { ok: false, reason }.
function buildMail(comments, readFile, token) {
  if (!/^[0-9a-f]{32}$/.test(String(token))) throw new Error("照合札は 32 字の16進数です (mail-route.js newToken)");
  comments = (comments || []).filter((c) => !c.user || c.user.login === OWNER);
  const plan = planSend(comments);
  if (!plan.ok) return plan;
  const { id, round, source } = plan.target;
  const src = comments.find((c) => c.id === source);
  // The files post-long.js pinned to a comment, read at that commit, whole. Earlier rounds' files too (Codex on PR #118).
  const pinned = (body) => {
    const p = String(body).match(/files=(\d+) sha=([0-9a-f]{40}) path=(consult\/[A-Za-z0-9-]+\/r\d+\/)/);
    const k = p ? Number(p[1]) : 0;
    return { n: k, read: (j) => String(readFile(`${p[3]}part-${j}.md`, p[2])).replace(/\r\n?/g, "\n").replace(/\s+$/, "") };
  };
  const { n, read } = pinned(src.body);
  const { limitOf, limitSpecified } = require("./post");
  const specified = limitSpecified(comments, id);
  const limit = specified ? limitOf(comments, id) : "なし";

  const out = [
    `【AMONE相談 v${VERSION} request=${id} round=${round} source=${source} parts=${n} limit=${limit}】`,
    "アムへ。モネからの相談です。GitHub は見に行かず、このメールの中身だけで答えてください。",
    `前の回と資料があれば先に読み、【相談本文】に日本語で答えてください。${specified ? `${limit}字以内で答えてください。` : "字数の指定はありません。問いに必要な長さで、結論から答えてください。"}答えの最後の行は「${endOfAnswer(id, round)}」にしてください。`,
    "【相談本文】", stripFooter(src.body),
  ];
  if (round > 1) {
    let k = 0;
    for (const c of comments) {
      if (c.id === source) break;
      const h = first(c.body), fl = fields(h);
      const same = (h.startsWith("[MONE-ASK]") || h.startsWith("[MONE-REPLY]")) ? fl.id === id
        : (h.startsWith("[AMU-ANSWER]") || h.startsWith("[MONE-RECORD]")) && fl.request === id && fl.status !== "blocked";
      if (!same) continue;
      out.push(`【前の回 ${++k}】`, stripFooter(c.body));
      const f = pinned(c.body);
      for (let j = 1; j <= f.n; j++) out.push(`【前の回 ${k} の資料 part-${j}/${f.n}】`, f.read(j));
    }
  }
  for (let k = 1; k <= n; k++) out.push(`【資料 part-${k}/${n}】`, read(k));
  const main = out.join("\n");
  const text = `${main}\n【相談おわり request=${id} round=${round} 本文=${len(main)}字】\n`;
  if (len(text) > MAX_MAIL_CHARS) {
    return { ok: false, reason: `メールが長すぎます (${len(text)}字。Chat に渡せるのは 4,500字まで)。相談を短くするか、分けてください` };
  }
  const send = { request: id, round, source, tag: tagOf(token) };
  return {
    ok: true, subject: MAIL_SUBJECT, body: `${tokenLine(token)}\n${text}`, chars: len(text), send,
    sendHead: `[MONE-SEND] request=${id} round=${round} source=${source} tag=${send.tag}`,
  };
}

// The reply body (after mail-reply.js normalizeReply). `open` is the waiting send (mail-route.js openSend).
// Returns { ok, tag, answer } or { ok: false, reason }. A reply without the end line is held (it may be cut).
function parseReply(text, open) {
  const lines = String(text || "").replace(/\r\n?/g, "\n").split("\n");
  const t = (lines[0] || "").trim().match(/^⟦AMONE-TOKEN ([0-9a-f]{32})⟧$/);
  if (!t) return { ok: false, reason: "1行目に照合札がありません。保留します" };
  const answer = lines.slice(1).join("\n").replace(/^\s+|\s+$/g, "");
  const last = answer.split("\n").pop().trim();
  // 2026-11-27 (MONE-IDEA-1): the iPhone side once returned the question itself. Name it, so the cause is found at once.
  if (last !== endOfAnswer(open.request, open.round) && /^【相談おわり request=/.test(last)) {
    return { ok: false, reason: "答えでなく、相談の原文がそのまま返っています (ショートカットのメール本文が、ChatGPT の答えでなく入力になっていないか確認してください)。保留します" };
  }
  if (last !== endOfAnswer(open.request, open.round)) {
    return { ok: false, reason: `答えの最後が「${endOfAnswer(open.request, open.round)}」ではありません (途中で切れたか、別の相談の答えです)。保留します` };
  }
  return { ok: true, tag: tagOf(t[1]), answer };
}

const sendBody = (head) => `${head}\nモネが通常Chatへ、この相談をメールで送ります (答え待ちのメールは全案件で1通だけ)。照合札そのものは書きません。\n\n次の担当: 通常Chat (iPhone のメール経由)\n`;

// The commands Monet runs. deps: { fetch() -> comments, readFile(path, sha), post(body) -> id, newToken(), write(file, text), read(file) }.
//   send <out-file>             take the slot ([MONE-SEND]) and write the mail body to <out-file> (outside the repository)
//   record <reply-file> html|text   check the reply and record it ([MONE-RECORD])
//   release                     free the slot without an answer ([MONE-SEND] status=release)
// --dry-run posts nothing. Nothing is retried automatically.
function cli(argv, deps, log = console.log) {
  const args = argv.filter((a) => a !== "--dry-run");
  const dry = args.length !== argv.length;
  const [cmd, file, kind] = args;
  const ng = (r) => { log("NG: " + r); return 1; };
  const { openSend, planRecord, recordBody } = require("./mail-route");
  let comments;
  try { comments = deps.fetch(); } catch (_) { return ng("GitHub から相談を読めませんでした (何も投稿していません)"); }
  // The thread holds 200 comments. A send takes 2 (its [MONE-SEND] and its record), so an accepted send can always be
  // recorded (Codex on PR #118): send needs room for both, record for its one.
  const full = (need) => comments.length + need > 200 ? "スレッドのコメントが 200 件に届きます。投稿せずに止まります。新しいスレッドへ引っ越してください" : null;
  if (cmd === "send" && file) {
    const m = buildMail(comments, deps.readFile, deps.newToken());
    if (!m.ok) return ng(m.reason);
    if (full(2)) return ng(full(2));
    deps.write(file, m.body);
    if (dry) { log(`DRY-RUN ${m.sendHead} ${m.chars}字 (投稿していません)`); return 0; }
    try { deps.post(sendBody(m.sendHead)); } catch (_) { return ng("[MONE-SEND] を投稿できませんでした。メールは送らないでください (自動では再試行しません)"); }
    log(`SEND-READY 件名=${m.subject} ${m.chars}字 ${m.sendHead}`);
    return 0;
  }
  if (cmd === "record" && file && ["html", "text"].includes(kind)) {
    const open = openSend(comments);
    if (!open) return ng("答え待ちのメールがありません。記録しません");
    const { normalizeReply } = require("./mail-reply");
    const r = normalizeReply(deps.read(file), kind);
    if (!r.ok) return ng(r.reason);
    const p = parseReply(r.text, open);
    if (!p.ok) return ng(p.reason);
    const plan = planRecord(comments, p.tag);
    if (!plan.ok) return ng(plan.reason);
    if (full(1)) return ng(full(1));
    if (dry) { log(`DRY-RUN 記録できます request=${open.request} round=${open.round} (投稿していません)`); return 0; }
    try { deps.post(recordBody(plan.send, p.answer)); } catch (_) { return ng("記録を投稿できませんでした (自動では再試行しません)"); }
    log(`RECORDED request=${open.request} round=${open.round}`);
    return 0;
  }
  if (cmd === "release") {
    const open = openSend(comments);
    if (!open) return ng("答え待ちのメールがありません");
    const head = `[MONE-SEND] request=${open.request} round=${open.round} source=${open.source} tag=${open.tag} status=release`;
    if (dry) { log(`DRY-RUN ${head}`); return 0; }
    try { deps.post(`${head}\n答えを待たずに、メールの枠を空けます。\n\n次の担当: モネ\n`); } catch (_) { return ng("投稿できませんでした (自動では再試行しません)"); }
    log(`RELEASED request=${open.request} round=${open.round}`);
    return 0;
  }
  log("使い方: node scripts/mail-send.js send <出力ファイル> | record <返信ファイル> html|text | release  [--dry-run]");
  return 1;
}

function realDeps() {
  const fs = require("node:fs");
  const os = require("node:os");
  const path = require("node:path");
  const post = require("./post");
  const REPO = "amukutsurogiwork-oss/ai-collab-sandbox";
  const pr = post.askPr();
  return {
    fetch: () => post.fetchAll(pr),
    readFile: (p, ref) => Buffer.from(post.run(["api", `repos/${REPO}/contents/${p}?ref=${ref}`, "--jq", ".content"]).trim(), "base64").toString("utf8"),
    newToken: require("./mail-route").newToken,
    write: (f, t) => {
      // the mail holds the token: never inside the repository
      if (!path.relative(path.join(__dirname, ".."), path.resolve(f)).startsWith("..")) throw new Error("出力ファイルはリポジトリの外に置いてください");
      fs.writeFileSync(f, t);
    },
    read: (f) => fs.readFileSync(f, "utf8"),
    post: (body) => {
      const f = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "mail-")), "body.md");
      fs.writeFileSync(f, body);
      return post.run(["api", `repos/${REPO}/issues/${pr}/comments`, "-F", `body=@${f}`, "--jq", ".id"]).trim();
    },
  };
}

if (require.main === module) {
  let code;
  try { code = cli(process.argv.slice(2), realDeps()); } catch (e) { console.log("NG: " + e.message); code = 1; }
  process.exit(code);
}

module.exports = { buildMail, parseReply, stripFooter, cli, MAX_MAIL_CHARS, MAIL_SUBJECT, VERSION };
