#!/usr/bin/env node
"use strict";

// Long consultations (Amu's design SLOTS-20261122): the body goes into numbered files in the consultation thread's branch,
// and the thread gets only a short marker comment (posted through post.js, so the thread budget still applies).
// Amu reads the files one by one at the named commit; a missing, duplicated or cut part makes her stop without answering.
// Usage: node scripts/post-long.js <file> [--dry-run]   (first line of <file> is the [MONE-ASK]/[MONE-REPLY] header)
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const MAX_PART_CHARS = 4500; // 90% of the 5,000 characters Amu reads at once
const MAX_PARTS = 6;
const chars = (s) => [...s];
const label = (id, round, k, n) => `[MONE-PART] id=${id} round=${round} part=${k}/${n}`;
const endMark = (id, round, k, n) => `【MONE-PART 終わり id=${id} round=${round} part=${k}/${n}】`;

function cut(body, room) {
  const cs = chars(body), out = [];
  let i = 0;
  while (i < cs.length) {
    let j = Math.min(cs.length, i + room);
    if (j < cs.length) {
      const nl = cs.slice(i, j).lastIndexOf("\n");
      if (nl > room / 2) j = i + nl + 1; // prefer to end a part right after a line break
    }
    out.push(cs.slice(i, j).join(""));
    i = j;
  }
  return out;
}

function splitParts(id, round, body) {
  if (!/^[A-Za-z0-9-]{1,64}$/.test(String(id))) throw new Error("相談の ID は英数字とハイフンだけにしてください");
  let n = 1;
  for (;;) {
    const room = MAX_PART_CHARS - chars(label(id, round, n, n)).length - chars(endMark(id, round, n, n)).length - 2;
    const pieces = cut(body, room);
    if (pieces.length > MAX_PARTS) throw new Error(`本文が長すぎます (${MAX_PARTS} ファイルをこえる)。相談を分けてください`);
    if (pieces.length === n) return pieces.map((p, i) => `${label(id, round, i + 1, n)}\n${p}\n${endMark(id, round, i + 1, n)}`);
    n = pieces.length;
  }
}

const partPath = (id, round, k) => `consult/${id}/r${round}/part-${k}.md`;
// exactly what is written to each file (already within the limit; nothing is added on write)
const partFiles = (id, round, body) => splitParts(id, round, body).map((content, i) => ({ path: partPath(id, round, i + 1), content }));

function markerComment(header, id, round, n, sha, summary) {
  const s = chars(String(summary || "")).slice(0, 300).join("");
  return `${header}\n長文の相談です。files=${n} sha=${sha} path=consult/${id}/r${round}/\n${s}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n`;
}

function parseLong(text) {
  const t = String(text).replace(/^\uFEFF/, "");
  const nl = t.indexOf("\n");
  const header = (nl < 0 ? t : t.slice(0, nl)).trim();
  const body = (nl < 0 ? "" : t.slice(nl + 1)).replace(/\n---\n_Generated by[\s\S]*$/, "").trim();
  const f = Object.fromEntries(header.replace(/^\[[^\]]+\]\s*/, "").split(/\s+/).filter((kv) => kv.includes("=")).map((kv) => kv.split("=")));
  return { header, body, id: f.id, round: Number(f.round) };
}

// Every check that post.js would make on the marker, plus "no other long ask is waiting", before anything is pushed.
function planLong(text, comments, now = new Date()) {
  const { header, body, id, round } = parseLong(text);
  if (!/^\[MONE-(ASK|REPLY)\]/.test(header) || !id || !round) return { ok: false, reason: "先頭行が [MONE-ASK] か [MONE-REPLY] ではありません" };
  let files;
  try { files = partFiles(id, round, body); } catch (e) { return { ok: false, reason: e.message }; }
  const summary = body.split("\n").find((l) => l.trim()) || "";
  const { planAsk, pendingKeys } = require("./post");
  const draft = planAsk(markerComment(header, id, round, files.length, "0".repeat(40), summary), comments, now);
  if (!draft.ok) return { ok: false, reason: draft.reason };
  for (const [key, b] of pendingKeys(comments)) {
    if (/files=\d+ sha=/.test(b)) return { ok: false, reason: `長文の相談 ${key.split(":")[0]} がまだ答えを待っています。ファイルを足すと、その相談の sha が古くなるので、答えが来てから出してください` };
  }
  return { ok: true, header, id, round, files, summary };
}

function main(argv) {
  const dry = argv.includes("--dry-run");
  const file = argv.find((a) => a !== "--dry-run");
  if (!file) { console.log("使い方: node scripts/post-long.js <ファイル> [--dry-run]"); return 1; }
  const text = fs.readFileSync(file, "utf8");
  const post = require("./post");
  let plan;
  try { plan = planLong(text, post.fetchAll(post.askPr())); } catch (_) { console.log("NG: GitHub から情報を取れませんでした(何も変えていません)"); return 1; }
  if (!plan.ok) { console.log("NG: " + plan.reason + " (何も変えていません)"); return 1; }
  const { header, id, round, files, summary } = plan;
  if (dry) { console.log(`DRY-RUN: ${files.length} ファイル (${files.map((f) => chars(f.content).length).join(", ")} 字)。投稿していません`); return 0; }
  const { askPr } = post;
  const repo = "amukutsurogiwork-oss/ai-collab-sandbox";
  const gh = (args) => execFileSync("gh", args, { encoding: "utf8" }).trim();
  const ref = gh(["api", `repos/${repo}/pulls/${askPr()}`, "--jq", ".head.ref"]);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "consult-"));
  const git = (args) => execFileSync("git", ["-C", dir, ...args], { encoding: "utf8" }).trim();
  execFileSync("git", ["clone", "-q", "--depth", "1", "-b", ref, `https://github.com/${repo}`, dir]);
  for (const f of files) {
    const fp = path.join(dir, f.path);
    fs.mkdirSync(path.dirname(fp), { recursive: true });
    fs.writeFileSync(fp, f.content);
  }
  git(["add", `consult/${id}/r${round}`]);
  git(["commit", "-q", "-m", `相談 ${id} round=${round} の本文 (${files.length} ファイル)`]);
  git(["push", "-q", "origin", ref]);
  const sha = git(["rev-parse", "HEAD"]);
  const marker = path.join(dir, "marker.md");
  fs.writeFileSync(marker, markerComment(header, id, round, files.length, sha, summary));
  // the marker goes through post.js: format check, duplicate check and the thread character budget
  return post.main(["ask", marker]);
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { splitParts, partPath, partFiles, planLong, markerComment, MAX_PARTS, MAX_PART_CHARS };
