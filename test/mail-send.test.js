"use strict";
// 2026-11-26 メール連携 ①④ (アストラの正式化案, よしひろさん「この形で作って」):
// iPhone に送るメールの本文を、相談PRの相談から作る。通常Chat は GitHub を見ないので、本文・前の回・資料をメールに全部入れる。
// 1行目は照合札 (ショートカットが ChatGPT に渡す前に外し、答えの前に付けて返す)。札は相談PRには書かない (tag だけ)。
const test = require("node:test");
const assert = require("node:assert");
const { buildMail, parseReply, MAX_MAIL_CHARS } = require("../scripts/mail-send.js");
const { tagOf } = require("../scripts/mail-route.js");

const c = (id, body) => ({ id, body });
const FOOT = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n";
const TOKEN = "0123456789abcdef0123456789abcdef";

test("the mail holds the token line first, then the ask whole without the GitHub footer, and an end line with the count", () => {
  const m = buildMail([c(10, "[MONE-ASK] id=A lane=chat op=design round=1 status=open\n問いの本文" + FOOT)], () => "", TOKEN);
  assert.equal(m.ok, true);
  const lines = m.body.split("\n");
  assert.equal(lines[0], `⟦AMONE-TOKEN ${TOKEN}⟧`);
  assert.equal(lines[1], "【AMONE相談 v1 request=A round=1 source=10 parts=0 limit=800】");
  assert.ok(m.body.includes("【相談本文】\n[MONE-ASK] id=A lane=chat op=design round=1 status=open\n問いの本文\n"));
  assert.ok(!m.body.includes("Generated by"));
  assert.ok(m.body.includes("最後の行は「【回答おわり request=A round=1】」"));
  const end = lines.filter(Boolean).pop();
  const counted = [...lines.slice(1, lines.lastIndexOf(end)).join("\n")].length;
  assert.equal(end, `【相談おわり request=A round=1 本文=${counted}字】`);
  assert.equal(m.chars, [...lines.slice(1).join("\n")].length);
  assert.equal(m.sendHead, `[MONE-SEND] request=A round=1 source=10 tag=${tagOf(TOKEN)}`);
  assert.ok(!m.sendHead.includes(TOKEN));
});

test("a design ask with limit=N passes that limit on", () => {
  const m = buildMail([c(10, "[MONE-ASK] id=A lane=chat op=design round=1 status=open limit=3000\n問い")], () => "", TOKEN);
  assert.match(m.body, /limit=3000】/);
  assert.ok(m.body.includes("3000字以内"));
});

test("a later round carries the earlier asks and answers (Amu's and Monet's records), and the files at the pinned sha", () => {
  const sha = "b".repeat(40);
  const comments = [
    c(1, "[MONE-ASK] id=A lane=chat op=design round=1 status=open\n一回目" + FOOT),
    c(2, "[MONE-RECORD] request=A round=1 source=1 tag=x\n答え1"),
    c(3, `[MONE-REPLY] id=A round=2\n長文の相談です。files=1 sha=${sha} path=consult/A/r2/\n二回目` + FOOT),
  ];
  const seen = [];
  const m = buildMail(comments, (p, ref) => { seen.push(`${p}@${ref}`); return "資料の中身"; }, TOKEN);
  assert.equal(m.ok, true);
  assert.deepEqual(seen, [`consult/A/r2/part-1.md@${sha}`]);
  assert.ok(m.body.includes("【前の回 1】\n[MONE-ASK] id=A lane=chat op=design round=1 status=open\n一回目\n"));
  assert.ok(m.body.includes("【前の回 2】\n[MONE-RECORD] request=A round=1 source=1 tag=x\n答え1\n"));
  assert.ok(m.body.includes("【資料 part-1/1】\n資料の中身\n"));
  assert.match(m.body.split("\n")[1], /request=A round=2 source=3 parts=1 /);
});

test("no mail while another mail waits, and none over the Chat input limit", () => {
  const ask = c(10, "[MONE-ASK] id=A lane=chat op=design round=1 status=open\n問い");
  const busy = buildMail([ask, c(11, "[MONE-SEND] request=A round=1 source=10 tag=ffff")], () => "", TOKEN);
  assert.equal(busy.ok, false);
  assert.match(busy.reason, /答え待ちのメールが1通あります/);
  const long = buildMail([c(10, "[MONE-ASK] id=A lane=chat op=design round=1 status=open\n" + "あ".repeat(MAX_MAIL_CHARS))], () => "", TOKEN);
  assert.equal(long.ok, false);
  assert.match(long.reason, /4,500字/);
});

test("a token must be the one-time hex form", () => {
  assert.throws(() => buildMail([c(10, "[MONE-ASK] id=A lane=chat op=design round=1 status=open\nq")], () => "", "short"));
});

test("the reply gives the token and the whole answer, only when it ends with the end line of that round", () => {
  const ok = parseReply(`⟦AMONE-TOKEN ${TOKEN}⟧\n答えの1行目\n答えの2行目\n【回答おわり request=A round=1】\n`, { request: "A", round: 1 });
  assert.equal(ok.ok, true);
  assert.equal(ok.tag, tagOf(TOKEN));
  assert.equal(ok.answer, "答えの1行目\n答えの2行目\n【回答おわり request=A round=1】");
  const cut = parseReply(`⟦AMONE-TOKEN ${TOKEN}⟧\n答えの1行目`, { request: "A", round: 1 });
  assert.equal(cut.ok, false);
  assert.match(cut.reason, /途中/);
  const other = parseReply(`⟦AMONE-TOKEN ${TOKEN}⟧\n答え\n【回答おわり request=B round=1】`, { request: "A", round: 1 });
  assert.equal(other.ok, false);
  const noTok = parseReply("答え\n【回答おわり request=A round=1】", { request: "A", round: 1 });
  assert.equal(noTok.ok, false);
  assert.match(noTok.reason, /照合札/);
});

test("a reply that is the question itself (the shortcut returned its input, not the answer) is held with a clear reason", () => {
  // 2026-11-27 MONE-IDEA-1: the iPhone side returned the original question. It must be named, not reported as just "cut".
  const echo = parseReply(`⟦AMONE-TOKEN ${TOKEN}⟧\n【AMONE相談 v1 request=A round=1 source=1 parts=0 limit=800】\n【相談本文】\n[MONE-ASK] id=A lane=chat op=review round=1 status=open\n問い\n【相談おわり request=A round=1 本文=10字】\n`, { request: "A", round: 1 });
  assert.equal(echo.ok, false);
  assert.match(echo.reason, /相談の原文/);
  assert.match(echo.reason, /入力/);
  // a real answer that merely mentions the words is still accepted when it ends with the end line
  const mention = parseReply(`⟦AMONE-TOKEN ${TOKEN}⟧\n答えの中で「【相談本文】」という言葉に触れる\n【回答おわり request=A round=1】`, { request: "A", round: 1 });
  assert.equal(mention.ok, true);
});

// The commands: take the slot, write the mail; then check the reply and record it. Nothing is posted on a dry run.
const { cli } = require("../scripts/mail-send.js");
function fake(comments, files = {}) {
  const posted = [], written = {}, logs = [];
  const deps = {
    fetch: () => comments, readFile: () => "", newToken: () => TOKEN,
    post: (b) => { posted.push(b); comments.push(c(100 + posted.length, b)); return 1; },
    write: (f, t) => { written[f] = t; }, read: (f) => files[f],
  };
  return { deps, posted, written, logs, log: (s) => logs.push(s) };
}

test("send posts [MONE-SEND] with the tag only, writes the mail; record checks the reply and posts [MONE-RECORD]; a second send waits", () => {
  const comments = [c(10, "[MONE-ASK] id=A lane=chat op=design round=1 status=open\n問い")];
  const f = fake(comments, { reply: `⟦AMONE-TOKEN ${TOKEN}⟧<br>答え<br>【回答おわり request=A round=1】` });
  assert.equal(cli(["send", "out"], f.deps, f.log), 0);
  assert.ok(f.posted[0].startsWith(`[MONE-SEND] request=A round=1 source=10 tag=${tagOf(TOKEN)}\n`));
  assert.ok(!f.posted[0].includes(TOKEN));
  assert.ok(f.written.out.startsWith(`⟦AMONE-TOKEN ${TOKEN}⟧\n`));
  assert.equal(cli(["send", "out2"], f.deps, f.log), 1);
  assert.match(f.logs.pop(), /答え待ちのメールが1通あります/);
  assert.equal(cli(["record", "reply", "html"], f.deps, f.log), 0);
  assert.ok(f.posted[1].startsWith(`[MONE-RECORD] request=A round=1 source=10 tag=${tagOf(TOKEN)}\n`));
  assert.ok(f.posted[1].includes("答え\n【回答おわり request=A round=1】"));
  assert.equal(cli(["record", "reply", "html"], f.deps, f.log), 1);
  assert.match(f.logs.pop(), /答え待ちのメールがありません/);
});

test("a reply with another token is held, and a dry run posts nothing", () => {
  const comments = [c(10, "[MONE-ASK] id=A lane=chat op=design round=1 status=open\n問い")];
  const f = fake(comments, { reply: `⟦AMONE-TOKEN ${"f".repeat(32)}⟧\n答え\n【回答おわり request=A round=1】` });
  assert.equal(cli(["send", "out", "--dry-run"], f.deps, f.log), 0);
  assert.equal(f.posted.length, 0);
  cli(["send", "out"], f.deps, f.log);
  assert.equal(cli(["record", "reply", "text"], f.deps, f.log), 1);
  assert.match(f.logs.pop(), /照合札が合いません/);
  assert.equal(cli(["release"], f.deps, f.log), 0);
  assert.match(f.posted.pop(), /^\[MONE-SEND\] request=A round=1 source=10 tag=\S+ status=release\n/);
});

// Codex (PR #118): the files of an earlier round sent by post-long.js must be in the mail too (Chat cannot fetch them).
test("the files pinned to earlier rounds are put in, each after its round, and count toward the size limit", () => {
  const s1 = "c".repeat(40);
  const comments = [
    c(1, `[MONE-ASK] id=A lane=chat op=design round=1 status=open\n長文の相談です。files=1 sha=${s1} path=consult/A/r1/\n一回目`),
    c(2, "[MONE-RECORD] request=A round=1 source=1 tag=x\n答え1"),
    c(3, "[MONE-REPLY] id=A round=2\n短い二回目"),
  ];
  const seen = [];
  const m = buildMail(comments, (p, ref) => { seen.push(`${p}@${ref}`); return "一回目の資料"; }, TOKEN);
  assert.equal(m.ok, true);
  assert.deepEqual(seen, [`consult/A/r1/part-1.md@${s1}`]);
  assert.ok(m.body.includes("【前の回 1】\n[MONE-ASK] id=A lane=chat op=design round=1 status=open\n長文の相談です。files=1 sha=" + s1 + " path=consult/A/r1/\n一回目\n【前の回 1 の資料 part-1/1】\n一回目の資料\n【前の回 2】"));
  const big = buildMail(comments, () => "あ".repeat(MAX_MAIL_CHARS), TOKEN);
  assert.equal(big.ok, false);
  assert.match(big.reason, /4,500字/);
});

// Codex (PR #118): a send must leave room for its own record, so an accepted send can always be recorded.
test("send stops early enough that its record still fits in the thread", () => {
  const filler = (n) => Array.from({ length: n }, (_, i) => c(1000 + i, "[MONE-NOTE] id=Z status=closed answer=1\nx"));
  const ask = c(10, "[MONE-ASK] id=A lane=chat op=design round=1 status=open\n問い");
  const reply = `⟦AMONE-TOKEN ${TOKEN}⟧\n答え\n【回答おわり request=A round=1】`;
  const f1 = fake([ask, ...filler(198)], { reply });
  assert.equal(cli(["send", "out"], f1.deps, f1.log), 1);
  assert.match(f1.logs.pop(), /引っ越し/);
  const f2 = fake([ask, ...filler(197)], { reply });
  assert.equal(cli(["send", "out"], f2.deps, f2.log), 0);
  assert.equal(cli(["record", "reply", "text"], f2.deps, f2.log), 0);
  assert.equal(f2.deps.fetch().length, 200);
});
